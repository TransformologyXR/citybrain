def validate_runtime_bundle() -> dict[str, Any]:
    checks = []
    one_truth = read_json(RUNTIME_BUNDLE / "one_truth_index.json", {})
    for item in one_truth.get("bundle_file_index", []):
        path = REPO_ROOT / item["path"]
        ok = path.exists() and sha256_file(path) == item["sha256"]
        checks.append({"check": f"hash:{item['file']}", "status": "PASS" if ok else "FAIL"})
    json_files = [path for path in RUNTIME_BUNDLE.glob("*.json")]
    for path in json_files:
        try:
            payload = read_json(path, {})
            ok = bool(payload.get("schema_version") and payload.get("scenario_state_ref"))
            if path.name == "one_truth_index.json":
                ok = payload.get("authority") == "one_truth_index"
            checks.append({"check": f"parse:{path.name}", "status": "PASS" if ok else "FAIL"})
        except Exception as exc:  # pragma: no cover
            checks.append({"check": f"parse:{path.name}", "status": "FAIL", "error": str(exc)})
    trace_ok = True
    rows = []
    with (RUNTIME_BUNDLE / "trace.jsonl").open("r", encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                rows.append(json.loads(line))
    trace_ok = len(rows) == 9 and rows[5]["stage_name"] == "SYNTHESIZE" and sum(1 for row in rows if row.get("narration_permitted")) == 1
    checks.append({"check": "trace_jsonl_9_stages_single_synthesize", "status": "PASS" if trace_ok else "FAIL"})
    checks.append({"check": "execution_state_not_executed", "status": "PASS" if one_truth.get("execution_state") == "not_executed" else "FAIL"})
    return {"status": "PASS" if all(row["status"] == "PASS" for row in checks) else "FAIL", "checks": checks}


