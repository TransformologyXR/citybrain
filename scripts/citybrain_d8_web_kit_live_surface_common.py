def bridge_event_for(command: dict[str, Any]) -> dict[str, Any]:
    command_name = command.get("command")
    base = {
        "schema_version": "citybrain-bridge-event-r1",
        "command_id": command.get("command_id"),
        "command": command_name,
        "scenario_state_ref": command.get("scenario_state_ref"),
        "execution_state": "not_executed",
        "timestamp_utc": now_iso(),
    }
    if command_name in ALLOWED_COMMANDS:
        return {**base, "command_status": "accepted", "reason": "review_command_allowed"}
    if command_name in FORBIDDEN_COMMANDS:
        return {**base, "command_status": "rejected", "reason": "review_only_boundary"}
    return {**base, "command_status": "rejected", "reason": "unknown_command"}


def run_bridge_smoke(output: Path) -> dict[str, Any]:
    ensure_bridge_dirs()
    one_truth = read_json(RUNTIME_BUNDLE / "one_truth_index.json", {})
    commands = [
        {"command_id": "cmd-allowed-select-001", "command": "select", "scenario_state_ref": one_truth["scenario_state_ref"], "entity_ref": "mobility_access:corridor:hero-lon-corridor", "execution_state": "not_executed"},
        {"command_id": "cmd-allowed-scrub-001", "command": "scrub", "scenario_state_ref": one_truth["scenario_state_ref"], "stage_name": "SYNTHESIZE", "execution_state": "not_executed"},
        {"command_id": "cmd-forbidden-approve-001", "command": "approve", "scenario_state_ref": one_truth["scenario_state_ref"], "execution_state": "not_executed"},
        {"command_id": "cmd-forbidden-dispatch-001", "command": "dispatch", "scenario_state_ref": one_truth["scenario_state_ref"], "execution_state": "not_executed"},
    ]
    events = []
    for command in commands:
        write_json(BRIDGE_ROOT / "inbox" / f"{command['command_id']}.json", command)
        event = bridge_event_for(command)
        events.append(event)
        write_json(BRIDGE_ROOT / "outbox" / f"{command['command_id']}.event.json", event)
    write_jsonl(BRIDGE_ROOT / "audit" / "bridge_audit.jsonl", events)
    write_jsonl(output / "BRIDGE_AUDIT.jsonl", events)
    allowed_ok = all(event["command_status"] == "accepted" for event in events if event["command"] in ALLOWED_COMMANDS)
    forbidden_ok = all(event["command_status"] == "rejected" and event["reason"] == "review_only_boundary" for event in events if event["command"] in FORBIDDEN_COMMANDS)
    report = {
        "status": "PASS" if allowed_ok and forbidden_ok else "FAIL",
        "allowed_command_count": sum(1 for event in events if event["command"] in ALLOWED_COMMANDS),
        "forbidden_command_count": sum(1 for event in events if event["command"] in FORBIDDEN_COMMANDS),
        "events": events,
        "bridge_audit_path": rel(BRIDGE_ROOT / "audit" / "bridge_audit.jsonl"),
    }
    return report


