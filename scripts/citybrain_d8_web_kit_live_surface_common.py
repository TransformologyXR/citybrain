def now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def rel(path: Path) -> str:
    try:
        return path.resolve().relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return str(path).replace("\\", "/")


def read_json(path: Path, default: Any = None) -> Any:
    if not path.exists():
        return default
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n")


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.rstrip() + "\n", encoding="utf-8", newline="\n")


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def write_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        for row in rows:
            handle.write(json.dumps(row, sort_keys=True) + "\n")


def status_from_decision(payload: Any) -> str | None:
    if not isinstance(payload, dict):
        return None
    return payload.get("status") or payload.get("final_status") or payload.get("decision_status")


def snapshot_root(root: Path) -> dict[str, Any]:
    if not root.exists():
        return {"exists": False, "file_count": 0, "byte_count": 0, "fingerprint": None}
    digest = hashlib.sha256()
    file_count = 0
    byte_count = 0
    for path in sorted(item for item in root.rglob("*") if item.is_file()):
        file_count += 1
        byte_count += path.stat().st_size
        digest.update(rel(path).encode("utf-8"))
        digest.update(str(path.stat().st_size).encode("utf-8"))
        digest.update(sha256_file(path).encode("utf-8"))
    return {"exists": True, "file_count": file_count, "byte_count": byte_count, "fingerprint": digest.hexdigest()}


def upstream_snapshots(specs: dict[str, dict[str, str]] = UPSTREAM_SPECS) -> dict[str, dict[str, Any]]:
    return {key: snapshot_root(REPO_ROOT / spec["root"]) for key, spec in specs.items()}


def discover_upstreams(specs: dict[str, dict[str, str]] = UPSTREAM_SPECS) -> tuple[dict[str, Any], dict[str, Any]]:
    rows = []
    missing = []
    for key, spec in specs.items():
        root = REPO_ROOT / spec["root"]
        decision_path = root / spec["decision_file"]
        decision = read_json(decision_path, {})
        status = status_from_decision(decision)
        expected = spec.get("expected")
        exists = root.exists() and decision_path.exists()
        green = bool(exists and status and status.startswith("PASS_"))
        if expected:
            green = green and status == expected
        row = {
            "key": key,
            "root": spec["root"],
            "decision_file": rel(decision_path),
            "exists": exists,
            "status": status,
            "expected_status": expected,
            "green": green,
            "role": spec.get("role"),
            "file_count": snapshot_root(root)["file_count"] if root.exists() else 0,
        }
        rows.append(row)
        if not green:
            missing.append(row)
    summary = {
        "status": "PASS" if not missing else "FAIL",
        "required_upstreams_found": len(rows) - len(missing),
        "required_upstreams_total": len(rows),
        "missing_or_not_green_count": len(missing),
        "missing_or_not_green": missing,
    }
    return {"generated_at_utc": now_iso(), "upstreams": rows, "summary": summary}, summary


def output_root(stage: str) -> Path:
    return OUTPUTS / STAGES[stage]["root"]


def prepare_root(stage: str) -> Path:
    root = output_root(stage)
    if root.resolve().parent != OUTPUTS.resolve():
        raise RuntimeError(f"Refusing unexpected output parent: {root}")
    if root.exists():
        shutil.rmtree(root)
    root.mkdir(parents=True, exist_ok=True)
    return root


def generated_files(root: Path) -> list[Path]:
    return sorted(path for path in root.rglob("*") if path.is_file())


def source_files(paths: list[Path]) -> list[Path]:
    rows: list[Path] = []
    for base in paths:
        if base.is_file():
            rows.append(base)
        elif base.exists():
            rows.extend(path for path in base.rglob("*") if path.is_file())
    return sorted(rows)


def hash_rows(paths: list[Path]) -> list[dict[str, Any]]:
    return [{"path": rel(path), "bytes": path.stat().st_size, "sha256": sha256_file(path)} for path in sorted(paths) if path.exists()]


def hash_manifest(root: Path, task_name: str, extra_paths: list[Path] | None = None) -> dict[str, Any]:
    files = [path for path in generated_files(root) if path.name != "HASH_MANIFEST.json"]
    if extra_paths:
        files.extend(source_files(extra_paths))
    seen: dict[str, Path] = {rel(path): path for path in files}
    rows = hash_rows(list(seen.values()))
    report = {
        "task_name": task_name,
        "timestamp_utc": now_iso(),
        "file_count": len(rows),
        "files": rows,
        "hash_validation_status": "PASS",
        "failures": [],
    }
    write_json(root / "HASH_MANIFEST.json", report)
    return report


def no_mutation_audit(root: Path, before: dict[str, dict[str, Any]], task_name: str) -> dict[str, Any]:
    after = upstream_snapshots()
    changed = [{"key": key, "before": prior, "after": after.get(key)} for key, prior in before.items() if prior != after.get(key)]
    report = {
        "task_name": task_name,
        "status": "PASS" if not changed else "FAIL",
        "checked_upstream_count": len(before),
        "changed_upstreams": changed,
        "policy": "This lane writes maintained source and its own additive output roots only; frozen upstream outputs are read-only.",
    }
    write_json(root / "NO_MUTATION_AUDIT.json", report)
    return report


def secret_audit(root: Path, task_name: str, extra_paths: list[Path] | None = None) -> dict[str, Any]:
    patterns = [
        re.compile(r"(?i)(api[_-]?key|secret|token|password)\s*[:=]\s*['\"]?[A-Za-z0-9_\-]{12,}"),
        re.compile(r"AKIA[0-9A-Z]{16}"),
        re.compile(r"-----BEGIN (?:RSA |OPENSSH |EC |DSA )?PRIVATE KEY-----"),
    ]
    paths = generated_files(root)
    if extra_paths:
        paths.extend(source_files(extra_paths))
    findings = []
    for path in paths:
        if path.suffix.lower() not in {".json", ".md", ".txt", ".html", ".js", ".py", ".toml", ".css"}:
            continue
        text = path.read_text(encoding="utf-8", errors="ignore")
        for pattern in patterns:
            if pattern.search(text):
                findings.append({"path": rel(path), "pattern": pattern.pattern})
    report = {"task_name": task_name, "status": "PASS" if not findings else "FAIL", "finding_count": len(findings), "findings": findings}
    write_json(root / "SECRET_AUDIT.json", report)
    return report


def claim_boundary_audit(root: Path, task_name: str, extra_paths: list[Path] | None = None) -> dict[str, Any]:
    affirming = []
    affirming_patterns = [
        "production ready",
        "public api ready",
        "certified citywide twin",
        "live autonomous monitoring",
        "automated execution",
    ]
    negation_tokens = ["no ", "not ", "does not", "do not", "never", "without", "false", "blocked", "forbidden", "rejected"]
    paths = generated_files(root)
    if extra_paths:
        paths.extend(source_files(extra_paths))
    for path in paths:
        if path.name.endswith("_AUDIT.json") or path.suffix.lower() not in {".json", ".md", ".txt", ".html", ".js", ".py"}:
            continue
        for idx, line in enumerate(path.read_text(encoding="utf-8", errors="ignore").splitlines(), 1):
            lower = line.lower()
            if any(pattern in lower for pattern in affirming_patterns) and not any(token in lower for token in negation_tokens):
                affirming.append({"path": rel(path), "line": idx, "text": line[:240]})
    report = {
        "task_name": task_name,
        "status": "PASS" if not affirming else "FAIL",
        "affirming_forbidden_claim_count": len(affirming),
        "affirming_forbidden_claims": affirming,
        "boundary": BOUNDARY,
        "prohibited_claims": [
            "production/public API readiness",
            "autonomous monitoring",
            "alerts",
            "dispatch/routing/control/enforcement",
            "legal/certified findings",
            "official ticket/case creation",
            "automated action",
        ],
    }
    write_json(root / "CLAIM_BOUNDARY_AUDIT.json", report)
    return report


