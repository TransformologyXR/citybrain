def validation_zip(root: Path) -> Path:
    zip_path = root / "WEB_KIT_LIVE_SURFACE_VALIDATION_PACKAGE.zip"
    include_roots = [output_root(stage) for stage in STAGE_ORDER]
    include_sources = [WEB_APP, KIT_APP, CONTRACTS, FIXTURE_ROOT]
    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for base in include_roots + include_sources:
            if not base.exists():
                continue
            for path in sorted(item for item in base.rglob("*") if item.is_file()):
                if path == zip_path:
                    continue
                archive.write(path, rel(path))
    return zip_path


