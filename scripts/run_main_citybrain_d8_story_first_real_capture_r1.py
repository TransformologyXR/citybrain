"""Run D8 story-first real capture R1 pack."""

from __future__ import annotations

import csv
import datetime as dt
import hashlib
import json
import re
from pathlib import Path
from typing import Any


REPO = Path(__file__).resolve().parents[1]

TASKS = {
    "capture": ("MAIN-CITYBRAIN-D8-STORY-FIRST-REAL-CAPTURE-R1", "outputs/main_citybrain_d8_story_first_real_capture_r1"),
    "media": ("MAIN-CITYBRAIN-D8-STORY-FIRST-REAL-MEDIA-IMPORT-R2", "outputs/main_citybrain_d8_story_first_real_media_import_r2"),
    "viewer": ("MAIN-CITYBRAIN-D8-STORY-FIRST-VIEWER-RECORD-IMPORT-R3", "outputs/main_citybrain_d8_story_first_viewer_record_import_r3"),
    "handoff": ("MAIN-CITYBRAIN-D8-STORY-FIRST-CAPTURE-VIEWER-HANDOFF-R4", "outputs/main_citybrain_d8_story_first_capture_viewer_handoff_r4"),
}

MEDIA_DIRS = [
    REPO / "inputs" / "d8_story_first_media",
    REPO / "outputs" / "manual_d8_story_first_media",
]

