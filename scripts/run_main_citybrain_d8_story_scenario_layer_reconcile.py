def run_evidence(layer: dict[str, Any]) -> None:
    root_path = root("evidence")
    root_path.mkdir(parents=True, exist_ok=True)
    scenario = layer["scenario"]
    records = {record["source_record_id"]: record for record in scenario["records"]}
    evidence_map = []
    missing = []
    limitations = {}
    for beat in scenario["beats"]:
        refs = beat["source_record_ids"]
        unsupported = [ref for ref in refs if ref not in records and not ref.startswith("limitation:")]
        if unsupported:
            missing.append({"beat_id": beat["beat_id"], "missing_refs": unsupported, "status": "DATA_DEPTH_GAP"})
        evidence_map.append(
            {
                "beat_id": beat["beat_id"],
                "beat_title": beat["title"],
                "viewer_claim": beat["viewer_copy"],
                "source_record_ids": refs,
                "support_status": "SUPPORTED_OR_LIMITED" if not unsupported else "DATA_DEPTH_GAP",
                "limitation": beat["limitation"],
            }
        )
        limitations[beat["beat_id"]] = beat["limitation"]
    write_json(root_path / "SCENARIO_TO_SOURCE_EVIDENCE_MAP.json", evidence_map)
    write_json(root_path / "SOURCE_RECORD_CARD_PAYLOADS.json", list(records.values()))
    write_json(root_path / "LIMITATION_BY_BEAT.json", limitations)
    write_json(
        root_path / "MISSING_EVIDENCE_LEDGER.json",
        {
            "status": "PASS_NO_UNDISCLOSED_MISSING_EVIDENCE" if not missing else "DATA_DEPTH_GAP",
            "timestamp": now(),
            "missing": missing,
            "explicit_limitations": scenario["limitations"],
        },
    )
    refs = [ref for item in evidence_map for ref in item["source_record_ids"]]
    no_fact_invention_audit(root_path / "NO_FACT_INVENTION_AUDIT.json", refs, scenario["limitations"])
    output_index(
        root_path,
        TASKS["evidence"][0],
        [
            "SCENARIO_TO_SOURCE_EVIDENCE_MAP.json",
            "SOURCE_RECORD_CARD_PAYLOADS.json",
            "LIMITATION_BY_BEAT.json",
            "MISSING_EVIDENCE_LEDGER.json",
            "NO_FACT_INVENTION_AUDIT.json",
            "HASH_MANIFEST.json",
        ],
    )
    write_hash(root_path)


