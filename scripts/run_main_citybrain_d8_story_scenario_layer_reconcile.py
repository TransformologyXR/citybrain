def main() -> int:
    for _, root_name in TASKS.values():
        (REPO / root_name).mkdir(parents=True, exist_ok=True)
    if not run_preflight():
        print(json.dumps({"status": "PARTIAL_SCENARIO_LAYER_NOT_ACCEPTABLE", "reason": "preflight gate failed"}, indent=2))
        return 1
    layer = make_scenario_layer()
    run_authoring(layer)
    run_evidence(layer)
    run_options(layer)
    dom_pass = run_dom_smoke()
    closeout_status = run_closeout(dom_pass)
    run_freeze(closeout_status)
    freeze_status = read_json(root("freeze") / "STORY_SCENARIO_LAYER_MILESTONE_FREEZE_DECISION.json")["status"]
    print(
        json.dumps(
            {
                "closeout_status": closeout_status,
                "freeze_status": freeze_status,
                "output_root": rel(root("freeze")),
                "dom_binding_status": "PASS" if dom_pass else "FAIL",
            },
            indent=2,
        )
    )
    return 0 if closeout_status == FINAL_PASS else 1


